CREATE DATABASE IF NOT EXISTS lalo_com CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE lalo_com;

CREATE TABLE IF NOT EXISTS admins (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at DATETIME NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS albums (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  client_name VARCHAR(120) NOT NULL,
  client_email VARCHAR(190) NULL,
  token CHAR(48) NOT NULL UNIQUE,
  created_at DATETIME NOT NULL,
  INDEX(token)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS photos (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  album_id BIGINT UNSIGNED NOT NULL,
  stored_name VARCHAR(100) NOT NULL UNIQUE,
  original_name VARCHAR(255) NOT NULL,
  mime_type VARCHAR(40) NOT NULL,
  file_size BIGINT UNSIGNED NOT NULL,
  created_at DATETIME NOT NULL,
  CONSTRAINT fk_photos_album FOREIGN KEY (album_id) REFERENCES albums(id) ON DELETE CASCADE,
  INDEX(album_id)
) ENGINE=InnoDB;